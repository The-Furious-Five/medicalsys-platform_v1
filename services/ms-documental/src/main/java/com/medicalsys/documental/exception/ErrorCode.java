package com.medicalsys.documental.exception;

import org.springframework.http.HttpStatus;

public enum ErrorCode {
    VALIDATION_ERROR(HttpStatus.BAD_REQUEST),
    MALFORMED_REQUEST(HttpStatus.BAD_REQUEST),
    UNAUTHENTICATED(HttpStatus.UNAUTHORIZED),
    FORBIDDEN(HttpStatus.FORBIDDEN),
    METHOD_NOT_ALLOWED(HttpStatus.METHOD_NOT_ALLOWED),
    UNSUPPORTED_MEDIA_TYPE(HttpStatus.UNSUPPORTED_MEDIA_TYPE),
    DOCUMENT_NOT_FOUND(HttpStatus.NOT_FOUND),
    RESOURCE_NOT_FOUND(HttpStatus.NOT_FOUND),
    DOCUMENT_LINK_ALREADY_EXISTS(HttpStatus.CONFLICT),
    DATA_INTEGRITY_CONFLICT(HttpStatus.CONFLICT),
    EMPTY_FILE(HttpStatus.UNPROCESSABLE_ENTITY),
    FILE_TOO_LARGE(HttpStatus.UNPROCESSABLE_ENTITY),
    FILE_TYPE_NOT_ALLOWED(HttpStatus.UNPROCESSABLE_ENTITY),
    INVALID_RETENTION_DATE(HttpStatus.UNPROCESSABLE_ENTITY),
    DOCUMENT_NOT_AVAILABLE(HttpStatus.UNPROCESSABLE_ENTITY),
    DOCUMENT_INTEGRITY_FAILURE(HttpStatus.INTERNAL_SERVER_ERROR),
    STORAGE_UNAVAILABLE(HttpStatus.SERVICE_UNAVAILABLE),
    CONSENT_TEMPLATE_NOT_FOUND(HttpStatus.NOT_FOUND),
    CONSENT_TEMPLATE_NOT_PUBLISHABLE(HttpStatus.CONFLICT),
    CONSENT_TEMPLATE_NOT_PUBLISHED(HttpStatus.UNPROCESSABLE_ENTITY),
    INFORMED_CONSENT_NOT_FOUND(HttpStatus.NOT_FOUND),
    INFORMED_CONSENT_INVALID_STATUS(HttpStatus.CONFLICT),
    PATIENT_CONTACT_UNAVAILABLE(HttpStatus.UNPROCESSABLE_ENTITY),
    PATIENT_SERVICE_UNAVAILABLE(HttpStatus.SERVICE_UNAVAILABLE),
    OTP_NOT_REQUESTED(HttpStatus.CONFLICT),
    OTP_EXPIRED(HttpStatus.UNPROCESSABLE_ENTITY),
    OTP_ATTEMPTS_EXCEEDED(HttpStatus.UNPROCESSABLE_ENTITY),
    OTP_INVALID(HttpStatus.UNPROCESSABLE_ENTITY),
    NOTIFICATION_DELIVERY_FAILED(HttpStatus.SERVICE_UNAVAILABLE),
    PDF_GENERATION_FAILED(HttpStatus.INTERNAL_SERVER_ERROR),
    INTERNAL_ERROR(HttpStatus.INTERNAL_SERVER_ERROR);

    private final HttpStatus status;

    ErrorCode(HttpStatus status) {
        this.status = status;
    }

    public HttpStatus status() {
        return status;
    }
}
