-- ms-agenda · scheduling_db · PostgreSQL 16
-- Modelo del Diccionario de Datos MedicalSys (seccion 8 - scheduling_db).
-- Las referencias a otros microservicios viajan como UUID publico y NO llevan FK fisica.

-- btree_gist permite combinar la igualdad de un UUID/BIGINT con el solapamiento de un rango
-- dentro de la misma restriccion EXCLUDE. Es lo que impide dobles reservas a nivel de motor.
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- ---------------------------------------------------------------- physical_resource
CREATE TABLE physical_resource (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id              UUID        NOT NULL DEFAULT gen_random_uuid(),
    organization_public_id UUID        NOT NULL,
    branch_public_id       UUID        NOT NULL,
    code                   VARCHAR(20) NOT NULL,
    name                   VARCHAR(120) NOT NULL,
    type                   VARCHAR(30) NOT NULL,
    floor                  VARCHAR(20),
    people_capacity        SMALLINT    NOT NULL DEFAULT 1,
    preparation_minutes    SMALLINT    NOT NULL DEFAULT 0,
    requires_sterilization BOOLEAN     NOT NULL DEFAULT FALSE,
    equipment              JSONB,
    status                 VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE',
    created_at             TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at             TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_physical_resource_public_id UNIQUE (public_id),
    CONSTRAINT uq_physical_resource_organization_public_id_code UNIQUE (organization_public_id, code),
    CONSTRAINT ck_physical_resource_type CHECK (type IN
        ('OFFICE','OPERATING_ROOM','PROCEDURE_ROOM','RECOVERY_ROOM','IMAGING_EQUIPMENT','LABORATORY','WAITING_ROOM')),
    CONSTRAINT ck_physical_resource_status CHECK (status IN
        ('AVAILABLE','OCCUPIED','UNDER_MAINTENANCE','OUT_OF_SERVICE')),
    CONSTRAINT ck_physical_resource_people_capacity CHECK (people_capacity >= 1),
    CONSTRAINT ck_physical_resource_preparation_minutes CHECK (preparation_minutes >= 0)
);

CREATE INDEX ix_physical_resource_branch_public_id_type_status
    ON physical_resource (branch_public_id, type, status);

-- ------------------------------------------------------------- schedule_availability
CREATE TABLE schedule_availability (
    id                                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    professional_organization_public_id UUID       NOT NULL,
    day_of_week                        SMALLINT    NOT NULL,
    start_time                         TIME        NOT NULL,
    end_time                           TIME        NOT NULL,
    slot_duration_minutes              SMALLINT    NOT NULL DEFAULT 30,
    simultaneous_capacity              SMALLINT    NOT NULL DEFAULT 1,
    modality                           VARCHAR(20) NOT NULL DEFAULT 'IN_PERSON',
    preferred_resource_id              BIGINT,
    valid_from                         DATE        NOT NULL,
    valid_until                        DATE,
    active                             BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at                         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_schedule_availability_professional_organization_p_key
        UNIQUE (professional_organization_public_id, day_of_week, start_time, valid_from),
    CONSTRAINT fk_schedule_availability_preferred_resource
        FOREIGN KEY (preferred_resource_id) REFERENCES physical_resource (id),
    CONSTRAINT ck_schedule_availability_day_of_week CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT ck_schedule_availability_time_range CHECK (end_time > start_time),
    CONSTRAINT ck_schedule_availability_slot_duration CHECK (slot_duration_minutes BETWEEN 5 AND 240),
    CONSTRAINT ck_schedule_availability_capacity CHECK (simultaneous_capacity >= 1),
    CONSTRAINT ck_schedule_availability_modality CHECK (modality IN ('IN_PERSON','TELECONSULTATION','BOTH')),
    CONSTRAINT ck_schedule_availability_validity CHECK (valid_until IS NULL OR valid_until >= valid_from)
);

CREATE INDEX ix_schedule_availability_professional_organization_p_key
    ON schedule_availability (professional_organization_public_id, active, valid_from, valid_until);
CREATE INDEX ix_schedule_availability_preferred_resource_id
    ON schedule_availability (preferred_resource_id);

-- -------------------------------------------------------------------- schedule_block
CREATE TABLE schedule_block (
    id                            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_public_id        UUID        NOT NULL,
    health_professional_public_id UUID,
    physical_resource_id          BIGINT,
    branch_public_id              UUID,
    type                          VARCHAR(20) NOT NULL,
    starts_at                     TIMESTAMPTZ NOT NULL,
    ends_at                       TIMESTAMPTZ NOT NULL,
    reason                        VARCHAR(250),
    created_by_user_public_id     UUID,
    created_at                    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_schedule_block_physical_resource
        FOREIGN KEY (physical_resource_id) REFERENCES physical_resource (id),
    CONSTRAINT ck_schedule_block_type CHECK (type IN
        ('VACATION','HOLIDAY','TRAINING','MAINTENANCE','EMERGENCY','CONFERENCE','OTHER')),
    CONSTRAINT ck_schedule_block_range CHECK (ends_at > starts_at),
    CONSTRAINT ck_schedule_block_target CHECK (
        health_professional_public_id IS NOT NULL
        OR physical_resource_id IS NOT NULL
        OR branch_public_id IS NOT NULL)
);

CREATE INDEX ix_schedule_block_health_professional_public_id_star_key
    ON schedule_block (health_professional_public_id, starts_at, ends_at);
CREATE INDEX ix_schedule_block_physical_resource_id_starts_at_ends_at
    ON schedule_block (physical_resource_id, starts_at, ends_at);
CREATE INDEX ix_schedule_block_branch_public_id_starts_at_ends_at
    ON schedule_block (branch_public_id, starts_at, ends_at);
CREATE INDEX ix_schedule_block_organization_public_id_starts_at
    ON schedule_block (organization_public_id, starts_at);
CREATE INDEX ix_schedule_block_created_by_user_public_id
    ON schedule_block (created_by_user_public_id);

-- ----------------------------------------------------------------------- appointment
CREATE TABLE appointment (
    id                            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id                     UUID        NOT NULL DEFAULT gen_random_uuid(),
    organization_public_id        UUID        NOT NULL,
    branch_public_id              UUID        NOT NULL,
    patient_public_id             UUID        NOT NULL,
    health_professional_public_id UUID        NOT NULL,
    service_offering_public_id    UUID        NOT NULL,
    starts_at                     TIMESTAMPTZ NOT NULL,
    ends_at                       TIMESTAMPTZ NOT NULL,
    modality                      VARCHAR(20) NOT NULL DEFAULT 'IN_PERSON',
    status                        VARCHAR(20) NOT NULL DEFAULT 'REQUESTED',
    channel_origin                VARCHAR(20) NOT NULL DEFAULT 'RECEPTION',
    reason_for_visit              VARCHAR(300),
    requires_consent              BOOLEAN     NOT NULL DEFAULT FALSE,
    estimated_price_bob           DECIMAL(12, 2),
    teleconsultation_link         VARCHAR(400),
    source_appointment_id         BIGINT,
    created_by_user_public_id     UUID,
    confirmed_at                  TIMESTAMPTZ,
    arrived_at                    TIMESTAMPTZ,
    care_started_at               TIMESTAMPTZ,
    care_ended_at                 TIMESTAMPTZ,
    cancelled_at                  TIMESTAMPTZ,
    cancelled_by_user_public_id   UUID,
    cancellation_reason           VARCHAR(300),
    created_at                    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_appointment_public_id UNIQUE (public_id),
    CONSTRAINT fk_appointment_source_appointment
        FOREIGN KEY (source_appointment_id) REFERENCES appointment (id),
    CONSTRAINT ck_appointment_modality CHECK (modality IN ('IN_PERSON','TELECONSULTATION')),
    CONSTRAINT ck_appointment_status CHECK (status IN
        ('REQUESTED','CONFIRMED','WAITING','IN_PROGRESS','ATTENDED','CANCELLED','NO_SHOW','RESCHEDULED')),
    CONSTRAINT ck_appointment_channel_origin CHECK (channel_origin IN
        ('WEB_PORTAL','MOBILE_APP','RECEPTION','PHONE','WHATSAPP')),
    CONSTRAINT ck_appointment_range CHECK (ends_at > starts_at),
    CONSTRAINT ck_appointment_price CHECK (estimated_price_bob IS NULL OR estimated_price_bob >= 0)
);

-- Antisolapamiento real: dos citas activas del mismo profesional no pueden cruzarse.
ALTER TABLE appointment
    ADD CONSTRAINT no_professional_overlap
    EXCLUDE USING gist (
        health_professional_public_id WITH =,
        tstzrange(starts_at, ends_at, '[)') WITH &&
    ) WHERE (status NOT IN ('CANCELLED','RESCHEDULED'));

CREATE INDEX ix_appointment_organization_public_id_branch_public__key
    ON appointment (organization_public_id, branch_public_id, starts_at);
CREATE INDEX ix_appointment_health_professional_public_id_starts__key
    ON appointment (health_professional_public_id, starts_at, ends_at);
CREATE INDEX ix_appointment_patient_public_id_starts_at
    ON appointment (patient_public_id, starts_at);
CREATE INDEX ix_appointment_organization_public_id_status_starts_at
    ON appointment (organization_public_id, status, starts_at);
CREATE INDEX ix_appointment_service_offering_public_id
    ON appointment (service_offering_public_id);
CREATE INDEX ix_appointment_source_appointment_id
    ON appointment (source_appointment_id);
CREATE INDEX ix_appointment_created_by_user_public_id
    ON appointment (created_by_user_public_id);
CREATE INDEX ix_appointment_cancelled_by_user_public_id
    ON appointment (cancelled_by_user_public_id);

-- --------------------------------------------------------------- resource_reservation
CREATE TABLE resource_reservation (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_public_id    UUID        NOT NULL,
    physical_resource_id      BIGINT      NOT NULL,
    appointment_id            BIGINT,
    starts_at                 TIMESTAMPTZ NOT NULL,
    ends_at                   TIMESTAMPTZ NOT NULL,
    purpose                   VARCHAR(200),
    status                    VARCHAR(20) NOT NULL DEFAULT 'RESERVED',
    created_by_user_public_id UUID,
    created_at                TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_resource_reservation_physical_resource
        FOREIGN KEY (physical_resource_id) REFERENCES physical_resource (id),
    CONSTRAINT fk_resource_reservation_appointment
        FOREIGN KEY (appointment_id) REFERENCES appointment (id),
    CONSTRAINT ck_resource_reservation_status CHECK (status IN ('RESERVED','IN_USE','RELEASED','CANCELLED')),
    CONSTRAINT ck_resource_reservation_range CHECK (ends_at > starts_at)
);

-- Un consultorio no puede quedar reservado dos veces en el mismo intervalo.
ALTER TABLE resource_reservation
    ADD CONSTRAINT no_resource_overlap
    EXCLUDE USING gist (
        physical_resource_id WITH =,
        tstzrange(starts_at, ends_at, '[)') WITH &&
    ) WHERE (status <> 'CANCELLED');

CREATE INDEX ix_resource_reservation_physical_resource_id_starts__key
    ON resource_reservation (physical_resource_id, starts_at, ends_at);
CREATE INDEX ix_resource_reservation_appointment_id
    ON resource_reservation (appointment_id);
CREATE INDEX ix_resource_reservation_organization_public_id_starts_at
    ON resource_reservation (organization_public_id, starts_at);
CREATE INDEX ix_resource_reservation_created_by_user_public_id
    ON resource_reservation (created_by_user_public_id);

-- --------------------------------------------------------- appointment_status_history
CREATE TABLE appointment_status_history (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id          BIGINT      NOT NULL,
    previous_status         VARCHAR(20),
    new_status              VARCHAR(20) NOT NULL,
    reason                  VARCHAR(300),
    user_account_public_id  UUID,
    origin                  VARCHAR(20) NOT NULL DEFAULT 'USER',
    occurred_at             TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_appointment_status_history_appointment
        FOREIGN KEY (appointment_id) REFERENCES appointment (id),
    CONSTRAINT ck_appointment_status_history_origin CHECK (origin IN ('USER','PATIENT','SYSTEM','WHATSAPP'))
);

CREATE INDEX ix_appointment_status_history_appointment_id_occurred_at
    ON appointment_status_history (appointment_id, occurred_at);
CREATE INDEX ix_appointment_status_history_user_account_public_id
    ON appointment_status_history (user_account_public_id);
